import { describe, expect, it } from 'vitest';
import { renderKnowledgeMarkdown, TABLE_SECTIONS } from '../../src/knowledge/render.ts';
import { buildTool, setPath, TODAY } from './builders.ts';

function sectionRows(markdown: string, heading: string): string[][] {
  const lines = markdown.split('\n');
  const start = lines.indexOf(`## ${heading}`);
  expect(start, `section "${heading}" exists`).toBeGreaterThanOrEqual(0);
  const rows: string[][] = [];
  for (const line of lines.slice(start + 1)) {
    if (line.startsWith('## ')) break;
    if (!line.startsWith('|')) continue;
    rows.push(
      line
        .slice(1, -1)
        .split(/(?<!\\)\|/)
        .map((cell) => cell.trim()),
    );
  }
  return rows.slice(2); // header and separator
}

const npm = buildTool('npm');
const renovate = buildTool('renovate', 'update-bot');
setPath(npm as unknown as Record<string, unknown>, 'cooldown.unit', {
  status: 'uncertain',
  note: 'Only the changelog mentions the unit.',
  value: 'days',
  source: 'https://github.com/npm/cli/blob/latest/CHANGELOG.md',
  verifiedAt: TODAY,
});
setPath(npm as unknown as Record<string, unknown>, 'cooldown.default', {
  status: 'disputed',
  note: 'Docs and release notes disagree.',
  variants: [
    { value: [{ since: '11.10.0', value: null }], source: 'https://docs.npmjs.com/cli/v11/using-npm/config', verifiedAt: TODAY },
    { value: [{ since: '11.10.0', value: 1 }], source: 'https://github.com/npm/cli/releases/tag/v11.10.0', verifiedAt: TODAY },
  ],
});
setPath(npm as unknown as Record<string, unknown>, 'cooldown.exclude.patternSyntax', {
  status: 'verified',
  value: 'a|b',
  source: 'https://docs.npmjs.com/cli/v11/using-npm/config#pipe',
  verifiedAt: TODAY,
});

const markdown = renderKnowledgeMarkdown([npm, renovate]);

describe('renderKnowledgeMarkdown', () => {
  it('marks the document as generated', () => {
    expect(markdown.split('\n', 1)[0]).toMatch(/^<!-- Generated by `npm run docs:knowledge`/);
    expect(markdown).toContain('# Package manager knowledge base');
  });

  it.each(TABLE_SECTIONS.map((section) => [section.heading, section.kinds]))(
    'renders rows for every eligible tool in "%s"',
    (heading, kinds) => {
      const labels = sectionRows(markdown, heading).map((row) => row[0] ?? '');
      expect(labels.some((label) => label.startsWith('Sample npm'))).toBe(true);
      expect(labels.some((label) => label.startsWith('Sample renovate'))).toBe(kinds.includes('update-bot'));
    },
  );

  it('renders one dependency-source row per source kind', () => {
    expect(sectionRows(markdown, 'Dependency sources').map((row) => row[0])).toEqual([
      'Sample npm · git',
      'Sample npm · remote tarball',
      'Sample npm · local tarball',
      'Sample npm · local directory',
    ]);
  });

  it.each(TABLE_SECTIONS.map((section) => [section.heading]))('links every cell in "%s" to its source', (heading) => {
    for (const row of sectionRows(markdown, heading)) {
      for (const cell of row.slice(1)) expect(cell).toMatch(/\]\(https:\/\/[^)]+\)/);
    }
  });

  it('shows a dash for details of a setting that does not exist', () => {
    const bun = buildTool('bun');
    setPath(bun as unknown as Record<string, unknown>, 'sources.git', {
      setting: { status: 'verified', value: null, source: 'https://bun.com/docs/pm/cli/add', verifiedAt: TODAY },
    });
    const [gitRow] = sectionRows(renderKnowledgeMarkdown([bun]), 'Dependency sources');
    expect(gitRow).toEqual(['Sample bun · git', 'none [↗](https://bun.com/docs/pm/cli/add)', '—', '—', '—']);
  });

  it('flags uncertain facts', () => {
    const [npmRow] = sectionRows(markdown, 'Release-age cooldown');
    expect(npmRow?.find((cell) => cell.includes('days'))).toContain('❓');
  });

  it('shows every variant of a disputed fact with its own source', () => {
    const [npmRow] = sectionRows(markdown, 'Release-age cooldown');
    const cell = npmRow?.find((value) => value.includes('⚠️')) ?? '';
    expect(cell).toContain('https://docs.npmjs.com/cli/v11/using-npm/config');
    expect(cell).toContain('https://github.com/npm/cli/releases/tag/v11.10.0');
  });

  it('escapes pipes inside values', () => {
    expect(markdown).toContain('a\\|b');
  });

  it('lists uncertain and disputed facts with their notes for review', () => {
    const review = markdown.slice(markdown.indexOf('## To review'));
    expect(review).toContain('Sample npm · `cooldown.unit` ❓ uncertain');
    expect(review).toContain('Only the changelog mentions the unit.');
    expect(review).toContain('Sample npm · `cooldown.default` ⚠️ disputed');
    expect(review).toContain('Docs and release notes disagree.');
  });

  it('says so when there is nothing to review', () => {
    expect(renderKnowledgeMarkdown([buildTool('pnpm')])).toContain('Nothing to review.');
  });

  it('ends with a single newline', () => {
    expect(markdown.endsWith('\n')).toBe(true);
    expect(markdown.endsWith('\n\n')).toBe(false);
  });
});
