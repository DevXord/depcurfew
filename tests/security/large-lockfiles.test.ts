// A large YAML lockfile from an untrusted repository cannot make doctor run for minutes or run out of memory: the yaml
// package's duplicate-key check is quadratic, so lockfiles are parsed without it and checked with a Set, once per
// run, and a YAML lockfile over the limit is reported by unreadable-config instead of being parsed.
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { cpuNow } from '../support/cpu-time.ts';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { detectProject } from '../../src/detect/index.ts';
import { Repository } from '../../src/detect/repository.ts';
import { runDoctor } from '../../src/doctor/index.ts';
import { MAX_YAML_LOCKFILE_SIZE, readLockfiles } from '../../src/doctor/lockfiles.ts';
import { knowledgeBase } from '../../src/knowledge/index.ts';

const temporary: string[] = [];
afterAll(() => {
  for (const directory of temporary) rmSync(directory, { recursive: true, force: true });
});

const POLICY = JSON.stringify({ version: 1, installScripts: { default: 'deny' }, sources: { git: 'deny', remoteTarball: 'deny' } });

function repository(files: Record<string, string>): string {
  const directory = mkdtempSync(join(tmpdir(), 'depcurfew-large-lockfiles-'));
  temporary.push(directory);
  for (const [file, text] of Object.entries(files)) writeFileSync(join(directory, file), text);
  return directory;
}

/** A pnpm-lock.yaml with `count` registry packages, every 997th from a git host, and their snapshots. */
function pnpmLock(count: number): string {
  const parts = ["lockfileVersion: '9.0'\n\nsettings:\n  autoInstallPeers: true\n  excludeLinksFromLockfile: false\n\nimporters:\n\n  .: {}\n\npackages:\n\n"];
  for (let index = 0; index < count; index++) {
    const resolution = index % 997 === 0 ? `{tarball: https://codeload.github.com/x/pkg-${index}/tar.gz/abc}` : `{integrity: sha512-${'A'.repeat(86)}==}`;
    parts.push(`  pkg-${index}@1.2.3:\n    resolution: ${resolution}\n    engines: {node: '>=18'}\n\n`);
  }
  parts.push('snapshots:\n\n');
  for (let index = 0; index < count; index++) parts.push(`  pkg-${index}@1.2.3:\n    dependencies:\n      pkg-${index + 1}: 1.2.3\n\n`);
  return parts.join('');
}

/** A Yarn Berry yarn.lock with `count` registry packages. */
function yarnLock(count: number): string {
  const parts = ['# This file is generated by running "yarn install" inside your project.\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n\n'];
  for (let index = 0; index < count; index++) {
    parts.push(
      `"pkg-${index}@npm:^1.0.0":\n  version: 1.2.3\n  resolution: "pkg-${index}@npm:1.2.3"\n  dependencies:\n    pkg-${index + 1}: "npm:^1.0.0"\n  checksum: 10c0/${'a'.repeat(128)}\n  languageName: node\n  linkType: hard\n\n`,
    );
  }
  return parts.join('');
}

function elapsed(action: () => void): number {
  const start = cpuNow();
  action();
  return cpuNow() - start;
}

describe('large YAML lockfiles', () => {
  // Before the fix 12 000 pnpm packages took 19 s; now 20 000 take about 2 s. The limit leaves room for slow CI.
  it('checks a pnpm-lock.yaml with 20 000 packages in seconds', { timeout: 120_000 }, () => {
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-lock.yaml': pnpmLock(20_000), 'depcurfew.json': POLICY });
    let findings: ReturnType<typeof runDoctor>['findings'] = [];
    expect(elapsed(() => (findings = runDoctor(root).findings))).toBeLessThan(20_000);
    expect(findings.filter((finding) => finding.rule === 'lockfile-forbidden-source')).toHaveLength(21);
    expect(findings.find((finding) => finding.rule === 'lockfile-forbidden-source')?.location).toEqual({ file: 'pnpm-lock.yaml', line: 13 });
  });

  // Before the fix 30 000 Yarn packages took about 45 s; now about 3 s.
  it('checks a Yarn Berry yarn.lock with 30 000 packages in seconds', { timeout: 120_000 }, () => {
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "yarn@4.12.0" }', 'yarn.lock': yarnLock(30_000), '.yarnrc.yml': 'nodeLinker: node-modules\n', 'depcurfew.json': POLICY });
    let report: ReturnType<typeof runDoctor> | undefined;
    expect(elapsed(() => (report = runDoctor(root)))).toBeLessThan(20_000);
    expect(report?.findings.filter((finding) => finding.rule === 'unreadable-config')).toEqual([]);
  });

  // Decision D-135: a minified lockfile has none of the anchors depcurfew looks for (`"node_modules/x": {` with a
  // space), and each one was looked for in the whole file twice: 10 000 npm entries took 10 s, 20 000 Composer
  // packages 33 s and 300 000 more than 5 minutes. Searches that miss now read at most a few times the file in all.
  it('checks a minified package-lock.json with 20 000 entries in seconds', { timeout: 120_000 }, () => {
    const packages: Record<string, unknown> = { '': { name: 'x' } };
    for (let index = 0; index < 20_000; index++) {
      packages[`node_modules/pkg-${index}`] =
        index % 997 === 0
          ? { version: '1.2.3', resolved: `git+ssh://git@github.com/x/pkg-${index}.git#${'a'.repeat(40)}` }
          : { version: '1.2.3', resolved: `https://registry.npmjs.org/pkg-${index}/-/pkg-${index}-1.2.3.tgz`, integrity: `sha512-${'A'.repeat(86)}==` };
    }
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "npm@11.16.0" }', 'package-lock.json': JSON.stringify({ name: 'x', lockfileVersion: 3, packages }), 'depcurfew.json': POLICY });
    let findings: ReturnType<typeof runDoctor>['findings'] = [];
    expect(elapsed(() => (findings = runDoctor(root).findings))).toBeLessThan(10_000);
    // The whole file is line 1; findings at one place that differ only in numbers are grouped after ten.
    const own = findings.filter((finding) => finding.rule === 'lockfile-forbidden-source');
    expect(own).toHaveLength(11);
    expect(own.map((finding) => finding.location)).toEqual(Array.from({ length: 11 }, () => ({ file: 'package-lock.json', line: 1 })));
  });

  it('checks a yarn.lock written as JSON, where no anchor matches, in seconds', { timeout: 120_000 }, () => {
    const document: Record<string, unknown> = { __metadata: { version: 8, cacheKey: '10c0' } };
    for (let index = 0; index < 20_000; index++) {
      const locator = index % 997 === 0 ? `https://code.example/x/pkg-${index}.tgz` : 'npm:1.2.3';
      document[`pkg-${index}@npm:^1.0.0`] = { version: '1.2.3', resolution: `pkg-${index}@${locator}`, checksum: `10c0/${'a'.repeat(128)}`, languageName: 'node', linkType: 'hard' };
    }
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "yarn@4.12.0" }', 'yarn.lock': JSON.stringify(document), '.yarnrc.yml': 'nodeLinker: node-modules\n', 'depcurfew.json': POLICY });
    let findings: ReturnType<typeof runDoctor>['findings'] = [];
    expect(elapsed(() => (findings = runDoctor(root).findings))).toBeLessThan(10_000);
    expect(findings.filter((finding) => finding.rule === 'lockfile-forbidden-source').length).toBeGreaterThan(0);
  });

  it('looks up the lines of 50 000 entries of a minified bun.lock in linear time', { timeout: 120_000 }, () => {
    const packages = Object.fromEntries(Array.from({ length: 50_000 }, (_, index) => [`pkg-${index}`, [`pkg-${index}@1.2.3`, '', {}, `sha512-${'A'.repeat(86)}==`]]));
    const root = repository({ 'package.json': '{ "name": "x" }', 'bun.lock': JSON.stringify({ lockfileVersion: 1, workspaces: { '': { name: 'x' } }, packages }) });
    const detection = detectProject(root);
    const manager = detection.packageManagers.find((item) => item.id === 'bun');
    const tool = knowledgeBase.find((item) => item.id === 'bun');
    if (manager === undefined || tool === undefined) throw new Error('Bun not detected');
    const [result] = readLockfiles(new Repository(root), manager, tool, [], knowledgeBase);
    if (result === undefined || !result.ok) throw new Error('bun.lock not read');
    const { entries, lineOf } = result.lockfile;
    expect(entries).toHaveLength(50_000);
    expect(elapsed(() => entries.forEach((item) => lineOf(item)))).toBeLessThan(3000);
  });

  it('looks up the lines of 50 000 packages of a minified composer.lock in linear time', { timeout: 120_000 }, () => {
    const packages = Array.from({ length: 50_000 }, (_, index) => ({ name: `vendor/pkg-${index}`, version: '1.2.3', dist: { type: 'zip', url: `https://api.github.com/repos/vendor/pkg-${index}/zipball/abc` } }));
    const root = repository({ 'composer.json': '{ "require": { "vendor/pkg-0": "^1" } }', 'composer.lock': JSON.stringify({ packages, 'packages-dev': [], 'plugin-api-version': '2.9.0' }) });
    const detection = detectProject(root);
    const manager = detection.packageManagers.find((item) => item.id === 'composer');
    const tool = knowledgeBase.find((item) => item.id === 'composer');
    if (manager === undefined || tool === undefined) throw new Error('Composer not detected');
    const [result] = readLockfiles(new Repository(root), manager, tool, [], knowledgeBase);
    if (result === undefined || !result.ok) throw new Error('composer.lock not read');
    const { entries, lineOf } = result.lockfile;
    expect(entries).toHaveLength(50_000);
    let lines: (number | undefined)[] = [];
    expect(elapsed(() => (lines = entries.map((item) => lineOf(item))))).toBeLessThan(3000);
    expect(new Set(lines)).toEqual(new Set([1]));
  });

  it('still finds the line of every entry of a pretty-printed lockfile when a few anchors are missing or written another way', () => {
    const entry = (index: number) =>
      index === 30 ? `    "node_modules/pkg-${index}"  :  { "version": "1.2.3" },\n` : `    "node_modules/pkg-${index}":${index === 10 || index === 20 ? '' : ' '}{ "version": "1.2.3" },\n`;
    const lock = `{\n  "name": "x",\n  "lockfileVersion": 3,\n  "packages": {\n    "": { "name": "x" },\n${Array.from({ length: 50 }, (_, index) => entry(index)).join('')}    "node_modules/last": { "version": "1.2.3" }\n  }\n}\n`;
    const root = repository({ 'package.json': '{ "name": "x" }', 'package-lock.json': lock });
    const detection = detectProject(root);
    const manager = detection.packageManagers.find((item) => item.id === 'npm');
    const tool = knowledgeBase.find((item) => item.id === 'npm');
    if (manager === undefined || tool === undefined) throw new Error('npm not detected');
    const [result] = readLockfiles(new Repository(root), manager, tool, [], knowledgeBase);
    if (result === undefined || !result.ok) throw new Error('package-lock.json not read');
    const lines = result.lockfile.entries.map((item) => result.lockfile.lineOf(item));
    // Entry 30 has an anchor depcurfew does not find; the minified spelling of 10 and 20 is found.
    expect(lines).toEqual([...Array.from({ length: 50 }, (_, index) => (index === 30 ? undefined : 6 + index)), 56]);
  });

  it('parses each lockfile once per run, for both lockfile rules', () => {
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-lock.yaml': pnpmLock(3), 'depcurfew.json': POLICY });
    const detection = detectProject(root);
    const manager = detection.packageManagers.find((entry) => entry.id === 'pnpm');
    const tool = knowledgeBase.find((entry) => entry.id === 'pnpm');
    if (manager === undefined || tool === undefined) throw new Error('pnpm not detected');
    const repo = new Repository(root);
    const first = readLockfiles(repo, manager, tool, [], knowledgeBase);
    expect(readLockfiles(repo, manager, tool, [], knowledgeBase)).toBe(first);
    expect(readLockfiles(new Repository(root), manager, tool, [], knowledgeBase)).not.toBe(first);
  });

  it('still reports duplicate keys, which the package managers reject, as unreadable-config', () => {
    const lock = `${pnpmLock(2)}  pkg-0@1.2.3:\n    resolution: {integrity: sha512-x}\n`;
    const line = lock.split('\n').length - 2;
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-lock.yaml': lock, 'depcurfew.json': POLICY });
    const findings = runDoctor(root).findings.filter((finding) => finding.rule === 'unreadable-config');
    expect(findings).toEqual([
      expect.objectContaining({ location: { file: 'pnpm-lock.yaml', line, column: 3 }, message: `cannot parse pnpm-lock.yaml: Map keys must be unique at line ${line}, column 3; depcurfew cannot check it` }),
    ]);
  });

  it('reports duplicate keys inside a flow mapping and in a boot document too', () => {
    const flow = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-lock.yaml': `${pnpmLock(1)}extra: {a: 1, a: 2}\n`, 'depcurfew.json': POLICY });
    expect(runDoctor(flow).findings.find((finding) => finding.rule === 'unreadable-config')?.message).toMatch(/^cannot parse pnpm-lock\.yaml: Map keys must be unique at line \d+, column \d+; /u);
    const boot = `---\nlockfileVersion: '9.0'\nimporters:\n  .:\n    configDependencies: {}\n    configDependencies: {}\n---\n${pnpmLock(1)}`;
    const booted = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@12.16.1" }', 'pnpm-lock.yaml': boot, 'depcurfew.json': POLICY });
    expect(runDoctor(booted).findings.find((finding) => finding.rule === 'unreadable-config')?.message).toBe(
      'cannot parse pnpm-lock.yaml: Map keys must be unique at line 6, column 5; depcurfew cannot check it',
    );
  });

  it('reports a YAML lockfile over the limit as unreadable-config instead of parsing it', () => {
    const lock = pnpmLock(1).padEnd(MAX_YAML_LOCKFILE_SIZE + 1, '#');
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-lock.yaml': lock, 'depcurfew.json': POLICY });
    const report = runDoctor(root);
    const megabytes = MAX_YAML_LOCKFILE_SIZE / (1024 * 1024);
    expect(report.findings.filter((finding) => finding.rule === 'unreadable-config')).toEqual([
      {
        rule: 'unreadable-config',
        level: 'error',
        location: { file: 'pnpm-lock.yaml' },
        message: `pnpm-lock.yaml is larger than ${megabytes} MiB, the limit for YAML lockfiles (parsing a larger one needs more memory than a CI runner gives Node.js), and was not read; depcurfew cannot check it`,
        fix: `Check where the packages in the lockfile come from and which have install scripts by hand; depcurfew reads YAML lockfiles up to ${megabytes} MiB and JSON lockfiles up to 64 MiB`,
      },
    ]);
  });
});

describe('large YAML configuration files', () => {
  // The duplicate-key check of the yaml package took 34 s for this file before; every YAML file depcurfew reads now
  // goes through the same linear check.
  it('reads a pnpm-workspace.yaml of 0.5 MiB with 50 000 keys in seconds', { timeout: 120_000 }, () => {
    const keys = Array.from({ length: 50_000 }, (_, index) => `k${index}: 1`).join('\n');
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-workspace.yaml': `minimumReleaseAge: 4320\n${keys}\n`, 'depcurfew.json': POLICY });
    let report: ReturnType<typeof runDoctor> | undefined;
    expect(elapsed(() => (report = runDoctor(root)))).toBeLessThan(15_000);
    expect(report?.findings.filter((finding) => finding.rule === 'unreadable-config')).toEqual([]);
  });

  it('reports a duplicate key in a configuration file as before', () => {
    const root = repository({ 'package.json': '{ "name": "x", "packageManager": "pnpm@10.26.0" }', 'pnpm-workspace.yaml': 'minimumReleaseAge: 4320\nminimumReleaseAge: 0\n', 'depcurfew.json': POLICY });
    expect(runDoctor(root).findings.filter((finding) => finding.rule === 'unreadable-config').map((finding) => finding.message)).toEqual([
      'cannot parse pnpm-workspace.yaml: Map keys must be unique at line 2, column 1; depcurfew cannot check it',
    ]);
  });
});
