function repository(files: Record<string, string | object>): string {
  const root = mkdtempSync(join(tmpdir(), 'depcurfew-d166-'));
  temporary.push(root);
  for (const [file, content] of Object.entries(files)) {
    mkdirSync(join(root, file, '..'), { recursive: true });
    writeFileSync(join(root, file), typeof content === 'string' ? content : `${JSON.stringify(content, null, 2)}\n`);
  }
  return root;
}

function report(root: string, rules = RULES) {
  return runDoctor(root, { policy: loadPolicyIfPresent(root) ?? null, rules });
}

/** Text of at least 2 MiB: the lines `line(index)` gives, until the size is reached. */
function sized(line: (index: number) => string, bytes = 2 * 1024 * 1024): string {
  const parts: string[] = [];
  let size = 0;
  for (let index = 0; size < bytes; index++) {
    const text = line(index);
    parts.push(text);
    size += text.length;
  }
  return parts.join('');
}

