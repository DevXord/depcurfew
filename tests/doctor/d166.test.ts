describe('apply does not write a file larger than it reads (decision D-166)', () => {
  it('refuses an edit after which the file would be over 1 MiB, with what to do', () => {
    const root = repository({ 'a.yml': `${'#'.repeat(MAX_FILE_SIZE - 10)}\n` });
    const workspace = new Workspace(root);
    expect(() => workspace.edit('a.yml', (body) => `${body}key: value\n`)).toThrow('a.yml would be larger than 1 MiB after this change, more than depcurfew reads, so depcurfew does not edit it');
    expect(workspace.problem('a.yml')).toEqual({ kind: 'result-too-large' });
    expect(workspace.changes()).toEqual([]);
    workspace.edit('a.yml', (body) => body.slice(0, 100));
    expect(workspace.changes()).toHaveLength(1);
  });

  it('a dependabot.yml that apply would grow past 1 MiB is not edited: cannot-edit, nothing written, the same on the next run', () => {
    const entries = Array.from({ length: 40 }, (_, index) => `  - package-ecosystem: npm\n    directory: /packages/p${index}\n    schedule:\n      interval: weekly\n`).join('');
    const head = 'version: 2\nupdates:\n';
    const padding = `# ${'x'.repeat(MAX_FILE_SIZE - head.length - entries.length - 200)}\n`;
    const dependabot = `${padding}${head}${entries}`;
    expect(dependabot.length).toBeLessThan(MAX_FILE_SIZE);
    const root = repository({ 'depcurfew.json': POLICY, 'package.json': { name: 'r', private: true, packageManager: 'npm@12.2.1' }, '.github/dependabot.yml': dependabot });
    for (let run = 0; run < 2; run++) {
      const plan = applyProject(root);
      expect(plan.failures).toEqual([
        {
          tool: 'dependabot',
          file: '.github/dependabot.yml',
          message: '.github/dependabot.yml would be larger than 1 MiB after this change, more than depcurfew reads, so depcurfew does not edit it',
          fix: 'Make .github/dependabot.yml smaller (for example by removing entries or comments it no longer needs), so that it stays under 1 MiB with the settings depcurfew adds, then run depcurfew apply again',
        },
      ]);
      expect(readFileSync(join(root, '.github/dependabot.yml'), 'utf8')).toBe(dependabot);
    }
  });
});

describe('script variables (decision D-166)', () => {
  it('reads export, NAME=value before a command and NAME=value written to $GITHUB_ENV', () => {
    const script = 'export A=1 B=2\nC=3 npm ci\nenv D=4 pnpm i\necho "E=5" >> "$GITHUB_ENV"\necho F=6 >>$GITHUB_ENV\nprintf \'%s\\n\' "G=7" "H=8" >> ${GITHUB_ENV}\necho -e \'I=9\\nJ=10\' > $GITHUB_ENV\necho K=11 >> other.env\necho "L<<EOF" >> "$GITHUB_ENV"\n';
    const { variables, commands } = readScript(script, 'GITHUB_ENV');
    expect(variables.map(({ name, value, how }) => `${how} ${name}=${value}`)).toEqual([
      'export A=1',
      'export B=2',
      'command C=3',
      'command D=4',
      'environment-file E=5',
      'environment-file F=6',
      'environment-file G=7',
      'environment-file H=8',
      'environment-file I=9',
      'environment-file J=10',
    ]);
    expect(commands.map((command) => command.words[0]?.text)).toEqual(['npm', 'pnpm', 'echo', 'echo', 'printf', 'echo', 'echo', 'echo']);
  });

  it('a Dockerfile has no environment file', () => {
    expect(readScript('echo "A=1" >> "$GITHUB_ENV"').variables).toEqual([]);
  });
});

describe('detection reads ARG and $GITHUB_ENV as the commands get them (decision D-166)', () => {
  const pip = (files: Record<string, string>) =>
    report(repository({ 'depcurfew.json': { version: 1, cooldown: { minimum: '3d' } }, 'requirements.txt': 'idna\n', ...files }), RULES.filter((rule) => rule.id === 'python-config-ignored')).findings.map((finding) => finding.location.line);

  it('an ARG of the stage, or one before FROM declared again, is a variable of RUN; ENV wins over it', () => {
    expect(pip({ Dockerfile: 'FROM python:3.13\nARG PIP_UPLOADED_PRIOR_TO=P3D\nRUN pip install -r requirements.txt\n' })).toEqual([]);
    expect(pip({ Dockerfile: 'ARG PIP_UPLOADED_PRIOR_TO=P3D\nFROM python:3.13\nARG PIP_UPLOADED_PRIOR_TO\nRUN pip install -r requirements.txt\n' })).toEqual([]);
    expect(pip({ Dockerfile: 'ARG PIP_UPLOADED_PRIOR_TO=P3D\nFROM python:3.13\nRUN pip install -r requirements.txt\n' })).toEqual([3]);
    expect(pip({ Dockerfile: 'FROM python:3.13 AS base\nARG PIP_UPLOADED_PRIOR_TO=P3D\nFROM base\nRUN pip install -r requirements.txt\n' })).toEqual([]);
    expect(pip({ Dockerfile: 'FROM python:3.13\nENV PIP_UPLOADED_PRIOR_TO=P1D\nARG PIP_UPLOADED_PRIOR_TO=P3D\nRUN pip install -r requirements.txt\n' })).toEqual([4]);
  });

  it('$GITHUB_ENV reaches the later steps of the job, not the step that writes it, and the env of a step wins', () => {
    const steps = (lines: string) => ({ '.github/workflows/ci.yml': `on: push\njobs:\n  b:\n    runs-on: ubuntu-latest\n    steps:\n${lines}` });
    expect(pip(steps('      - run: echo "PIP_UPLOADED_PRIOR_TO=P3D" >> "$GITHUB_ENV"\n      - run: pip install -r requirements.txt\n'))).toEqual([]);
    expect(pip(steps('      - run: |\n          echo "PIP_UPLOADED_PRIOR_TO=P3D" >> "$GITHUB_ENV"\n          pip install -r requirements.txt\n'))).toEqual([8]);
    expect(pip(steps('      - run: echo "PIP_UPLOADED_PRIOR_TO=P3D" >> "$GITHUB_ENV"\n      - run: pip install -r requirements.txt\n        env:\n          PIP_UPLOADED_PRIOR_TO: P1D\n'))).toEqual([7]);
  });
});

