// known-malicious reads the yarn.lock of Yarn Classic (decision D-165): the v1 format, as the parser of Yarn 1.22.22
// reads it, and the tarball of resolved, which Yarn Classic fetches, as the version looked up. Yarn Classic stays
// unsupported for settings.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { run } from '../../src/cli/run.ts';
import { runDoctor, type DoctorReport } from '../../src/doctor/index.ts';
import { lockedVersions, runDoctorWithLocalOsv, runDoctorWithOsv } from '../../src/doctor/osv.ts';
import { NO_DATA_FIX, NO_DATA_MESSAGE } from '../../src/doctor/rules/known-malicious.ts';
import { classicYarnEntries } from '../../src/doctor/yarn-classic-lockfile.ts';
import { extraOf, isRecord } from '../../src/apply/facts.ts';
import { yarn } from '../../src/knowledge/yarn.ts';
import { LocalOsvData } from '../../src/osv/data.ts';
import { osvFetch } from '../support/osv.ts';
import { localData } from '../support/osv-data.ts';

const NOW = new Date('2026-11-02T18:00:00Z');
const temporary: string[] = [];
afterAll(() => {
  for (const directory of temporary) rmSync(directory, { recursive: true, force: true });
});

function repository(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'depcurfew-yarn-classic-'));
  temporary.push(root);
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), text);
  }
  return root;
}

const HEADER = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n';
const MANIFEST = '{\n  "name": "app",\n  "version": "1.0.0"\n}\n';
const classic = (lock: string, extra: Record<string, string> = {}) => repository({ 'package.json': MANIFEST, 'yarn.lock': `${HEADER}${lock}`, ...extra });
const looked = (root: string) => lockedVersions(root, { policy: null }).map((entry) => `${entry.ecosystem}:${entry.name}@${entry.version}`);
const own = (report: DoctorReport) => report.findings.filter((finding) => finding.rule === 'known-malicious').map(({ level, location, message, fix }) => ({ level, location, message, fix }));

const REGISTRY = 'https://registry.yarnpkg.com';
const MAL = 'MAL-2026-18458 (https://osv.dev/vulnerability/MAL-2026-18458)';

/** A lockfile as Yarn 1.22 writes it: several patterns on one key line, quoted keys, nested dependencies, aliases. */
const LOCK = [
  '"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":',
  '  version "7.12.13"',
  `  resolved "${REGISTRY}/@babel/code-frame/-/code-frame-7.12.13.tgz#dade5d6d9e2a1d7b1c5e3e4f9a0b1c2d3e4f5a6b"`,
  '  integrity sha512-HV1Cm0Q3ZrpCR93tkWOYiuYIgLxZXZFVG2VgK+MBWjUqZTundupbfx2aXarXuw5Ko5aMcjtJgbSs4vUGBS5v6g==',
  '  dependencies:',
  '    "@babel/highlight" "^7.12.13"',
  '',
  'cutekitten-test@^1.0.0:',
  '  version "1.0.1"',
  `  resolved "${REGISTRY}/cutekitten-test/-/cutekitten-test-1.0.1.tgz#0000000000000000000000000000000000000000"`,
  '',
  '"innocent@npm:evil-pkg@1.0.0":',
  '  version "1.0.0"',
  `  resolved "${REGISTRY}/evil-pkg/-/evil-pkg-1.0.0.tgz#abc"`,
  '',
  '"local@file:./local":',
  '  version "1.0.0"',
  '',
  '"gitdep@git+https://github.com/o/r.git#abc":',
  '  version "1.0.0"',
  '  resolved "git+https://github.com/o/r.git#0123456789abcdef0123456789abcdef01234567"',
  '',
  'short@o/r:',
  '  version "1.0.0"',
  '  resolved "https://codeload.github.com/o/r/tar.gz/0123456789abcdef0123456789abcdef01234567"',
  '',
  '"tarball@https://example.com/tarball-2.0.0.tgz":',
  '  version "2.0.0"',
  '  resolved "https://example.com/tarball-2.0.0.tgz"',
  '',
].join('\n');

describe('known-malicious reads the yarn.lock of Yarn Classic', () => {
  it('looks up the registry tarball of resolved of every entry, once for a key line with several patterns', () => {
    expect(looked(classic(LOCK))).toEqual(['npm:@babel/code-frame@7.12.13', 'npm:cutekitten-test@1.0.1', 'npm:evil-pkg@1.0.0']);
  });

  it('reports a malicious version at the line of its key, with --osv and with the local data', async () => {
    const root = classic(LOCK);
    const expected = [
      {
        level: 'error',
        location: { file: 'yarn.lock', line: 12 },
        message: `yarn.lock locks cutekitten-test@1.0.1, a known malicious version: OSV.dev lists it as ${MAL}`,
        fix: 'Remove cutekitten-test@1.0.1 from the project: update or replace the package and lock again. If it was installed anywhere, read the record on OSV.dev for what it does and treat that machine as exposed',
      },
    ];
    expect(own(await runDoctorWithOsv(root, { policy: null }, { fetch: osvFetch() }))).toEqual(expected);
    const local = new LocalOsvData(await localData(temporary, NOW));
    expect(own(runDoctorWithLocalOsv(root, { policy: null }, local, NOW))).toEqual(expected);
  });

  it('reads the file as Yarn 1 does: CR LF, comments, later keys and fields win, references and a merge conflict', () => {
    const lock = [
      '# a comment',
      'a@^1.0.0:',
      '  version "1.0.0"',
      `  resolved "${REGISTRY}/a/-/a-1.0.0.tgz#x"`,
      '',
      // The same pattern again: Yarn keeps the last one.
      'a@^1.0.0:',
      '  version "1.2.0"',
      `  resolved "${REGISTRY}/a/-/a-1.1.0.tgz#x"`,
      `  resolved "${REGISTRY}/a/-/a-1.2.0.tgz#x"`,
      '',
      // A key whose value is another pattern, which Yarn follows.
      '"b@^2.0.0" "b@2.0.0"',
      '',
      'b@2.0.0:',
      '  version "2.0.0"',
      `  resolved "${REGISTRY}/b/-/b-2.0.0.tgz#y"`,
      '',
      '<<<<<<< HEAD',
      'c@^3.0.0:',
      '  version "3.0.0"',
      `  resolved "${REGISTRY}/c/-/c-3.0.0.tgz#z"`,
      '=======',
      'c@^3.0.0:',
      '  version "3.1.0"',
      `  resolved "${REGISTRY}/c/-/c-3.1.0.tgz#z"`,
      '>>>>>>> branch',
      '',
    ].join('\r\n');
    // Yarn merges the two sides of a conflict, the second winning, and installs from the result.
    expect(looked(classic(lock))).toEqual(['npm:a@1.2.0', 'npm:b@2.0.0', 'npm:c@3.1.0']);
  });

  it('warns when the version field or the name of an entry says otherwise than its resolved tarball', async () => {
    const lock = ['lodash@^4.17.0:', '  version "4.17.21"', `  resolved "${REGISTRY}/cutekitten-test/-/cutekitten-test-1.0.1.tgz#0"`, ''].join('\n');
    const root = classic(lock);
    expect(looked(root)).toEqual(['npm:cutekitten-test@1.0.1']);
    const findings = own(await runDoctorWithOsv(root, { policy: null }, { fetch: osvFetch() }));
    expect(findings).toContainEqual({
      level: 'warning',
      location: { file: 'yarn.lock', line: 5 },
      message:
        'yarn.lock has lodash@^4.17.0 as lodash@4.17.21, but its resolved URL is the registry tarball of cutekitten-test@1.0.1, which is what Yarn Classic fetches; known-malicious checked cutekitten-test@1.0.1',
      fix: 'Find out who changed this entry of yarn.lock (Yarn Classic writes the version of the package whose tarball it resolves, under the name the entry declares, so an entry where they differ was edited), then lock the package again with Yarn Classic',
    });
    expect(findings.map((finding) => finding.level)).toContain('error');
  });

  it('warns about a registry entry without resolved, which Yarn Classic resolves again', async () => {
    const lock = ['a@^1.0.0:', '  version "1.0.0"', '', '"local@link:../local":', '  version "0.0.0"', ''].join('\n');
    const findings = own(await runDoctorWithOsv(classic(lock), { policy: null }, { fetch: osvFetch() }));
    expect(findings).toEqual([
      {
        level: 'warning',
        location: { file: 'yarn.lock', line: 5 },
        message: 'known-malicious could not check 1 registry package of yarn.lock, whose entry gives no exact version that Yarn Classic installs: a (line 5)',
        fix: 'Lock this package again with Yarn Classic, so that yarn.lock names its exact version, and find out why it does not; then run depcurfew doctor --osv again',
      },
    ]);
  });

  it('a yarn.lock that Yarn 1 cannot read is an unreadable lockfile', async () => {
    const root = classic('a@^1.0.0:\n   version "1.0.0"\n');
    const report = await runDoctorWithOsv(root, { policy: null }, { fetch: osvFetch() });
    expect(report.findings.filter((finding) => finding.rule === 'unreadable-config').map((finding) => [finding.level, finding.location.file])).toEqual([['error', 'yarn.lock']]);
  });

  it('a lockfile of a later format version is a note, as Yarn 1.22 refuses it', async () => {
    const root = repository({ 'package.json': MANIFEST, 'yarn.lock': '# yarn lockfile v1\n# yarn lockfile v2\n\na@^1.0.0:\n  version "1.0.0"\n' });
    const report = await runDoctorWithOsv(root, { policy: null }, { fetch: osvFetch() });
    expect(own(report)).toEqual([]);
    expect(report.notices).toContainEqual(expect.objectContaining({ code: 'known-malicious', message: 'known-malicious could not check yarn.lock: it is a yarn lockfile v2, and Yarn Classic reads only version 1' }));
  });

  it('without --osv and without local data, says how to get them, at yarn.lock', () => {
    const report = runDoctor(classic(LOCK), { policy: null, osv: { unavailable: true } });
    expect(report.notices).toContainEqual(expect.objectContaining({ code: 'known-malicious', location: { file: 'yarn.lock' }, message: NO_DATA_MESSAGE, fix: NO_DATA_FIX }));
  });

  it('doctor --osv on a Yarn Classic project fails on a malicious version, and Yarn Classic stays unsupported for settings', async () => {
    let stdout = '';
    const code = await run(['doctor', '--json', '--osv', classic(LOCK)], { stdout: (text) => (stdout += text), stderr: () => {} }, { fetch: osvFetch(), now: () => NOW, stdin: async () => '', osvData: () => undefined });
    const report = JSON.parse(stdout) as DoctorReport;
    expect(code).toBe(1);
    expect(report.findings.filter((finding) => finding.rule === 'known-malicious').map((finding) => finding.location)).toEqual([{ file: 'yarn.lock', line: 12 }]);
    expect(report.checked?.tools).toEqual([]);
    expect(report.findings.filter((finding) => ['lockfile-forbidden-source', 'lockfile-install-scripts'].includes(finding.rule))).toEqual([]);
  });
});

describe('the reader of the Yarn Classic yarn.lock runs in linear time', () => {
  const format = extraOf(yarn, 'classicLockfile', isRecord);
  const timed = (text: string) => {
    const start = performance.now();
    let result: unknown;
    try {
      result = classicYarnEntries(text, format, undefined).length;
    } catch (error) {
      result = (error as Error).message;
    }
    return { seconds: (performance.now() - start) / 1000, result };
  };

  it('reads 100 000 entries of a 30 MiB lockfile in seconds', { timeout: 120_000 }, () => {
    const parts = [HEADER];
    for (let index = 0; index < 100_000; index++) {
      parts.push(`"pkg-${index}@^1.0.0", "pkg-${index}@^1.2.0":\n  version "1.2.3"\n  resolved "${REGISTRY}/pkg-${index}/-/pkg-${index}-1.2.3.tgz#${'0'.repeat(40)}"\n  integrity sha512-${'A'.repeat(86)}==\n  dependencies:\n    "pkg-${index + 1}" "^1.0.0"\n\n`);
    }
    const { seconds, result } = timed(parts.join(''));
    expect(result).toBe(100_000);
    expect(seconds).toBeLessThan(15);
  });

  it.each([
    ['a quote that never closes', `a@^1:\n  version "${'x'.repeat(4 * 1024 * 1024)}`],
    ['backslashes before quotes', `a@^1:\n  version "${'\\\\"'.repeat(1024 * 1024)}"\n`],
    ['one key line with a million patterns', `${'a@^1, '.repeat(1024 * 1024)}a@^1:\n  version "1.0.0"\n`],
    ['a million blank lines inside an entry', `a@^1:\n${'  \n'.repeat(1024 * 1024)}  version "1.0.0"\n`],
    ['nesting deeper than any lockfile', Array.from({ length: 2000 }, (_, depth) => `${'  '.repeat(depth)}k:`).join('\n')],
  ])('%s', { timeout: 60_000 }, (_case, text) => {
    expect(timed(text).seconds).toBeLessThan(5);
  });
});
