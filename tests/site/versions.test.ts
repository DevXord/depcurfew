const CHANGELOG_120 = ['# Changelog', '', '## 1.2.0', '', '- The item of one two.', '', CHANGELOG_110.slice(CHANGELOG_110.indexOf('## 1.1.0'))].join('\n');
const SCHEMA_110 = '{\n  "title": "schema of 1.1.0"\n}\n';
const SCHEMA_120 = '{\n  "title": "schema of 1.2.0"\n}\n';
const pkg = (version: string, repository = 'git+https://github.com/DevXord/depcurfew.git') =>
  `${JSON.stringify({ name: 'depcurfew', version, description: `depcurfew ${version} description`, license: 'MIT', repository: { type: 'git', url: repository } }, null, 2)}\n`;

beforeAll(() => {
  repository = mkdtempSync(join(tmpdir(), 'depcurfew-site-git-'));
  plain = mkdtempSync(join(tmpdir(), 'depcurfew-site-plain-'));
  writeFileSync(join(plain, 'gitconfig'), '');
  gitEnvironment = { ...environment, GIT_CONFIG_GLOBAL: join(plain, 'gitconfig'), GIT_CONFIG_NOSYSTEM: '1' };
  git('init', '--quiet');
  commit('v1.0.0', { 'README.md': '# depcurfew\n\nVersion one zero.\n', 'package.json': pkg('1.0.0') });
  commit('v1.1.0', { 'README.md': README_110, 'docs/knowledge.md': KNOWLEDGE_110, 'CHANGELOG.md': CHANGELOG_110, 'schema.json': SCHEMA_110, 'package.json': pkg('1.1.0', 'git+https://github.com/old-owner/depcurfew.git') });
  commit('v1.1.1', { 'README.md': null, 'package.json': pkg('1.1.1') });
  // An annotated tag, without docs/knowledge.md.
  commit('v1.2.0', { 'README.md': '# depcurfew\n\nVersion one two, facts in [docs/knowledge.md](https://github.com/DevXord/depcurfew/blob/main/docs/knowledge.md).\n', 'docs/knowledge.md': null, 'CHANGELOG.md': CHANGELOG_120, 'schema.json': SCHEMA_120, 'package.json': pkg('1.2.0') }, true);
  commit('v2.0.0-rc.1', { 'package.json': pkg('2.0.0-rc.1') });
  commit(`v${current}`, { 'package.json': pkg(current) });
  commit(`v${newer}`, { 'package.json': pkg(newer) });
  git('tag', 'vnext');
  git('tag', 'release-1.3.0');

  versions = readVersions(repository, current, (line) => report.push(line));
  outputs = [mkdtempSync(join(tmpdir(), 'depcurfew-site-')), mkdtempSync(join(tmpdir(), 'depcurfew-site-'))];
  site = outputs[0] ?? '';
  for (const directory of outputs) buildSite(directory, ROOT, { versions, report: (line) => report.push(line) });
});

afterAll(() => {
  for (const directory of [repository, plain, ...outputs]) if (directory !== '') rmSync(directory, { recursive: true, force: true });
});

const ROOT_PAGES = [...SITE_PAGES.map((entry) => entry.file), VERSIONS_PAGE.file];
const ARCHIVE = ['1.1.0/changelog.html', '1.1.0/index.html', '1.1.0/knowledge.html', '1.1.0/schema.json', '1.2.0/changelog.html', '1.2.0/index.html', '1.2.0/schema.json'];
const FILES = [...ROOT_PAGES, 'favicon.svg', 'schema.json', 'schema/v1.json', 'style.css', ...ARCHIVE].sort();
const HTML = FILES.filter((name) => name.endsWith('.html'));
const page = (name: string) => readPage(site, name);

describe('reading the release tags', () => {
  it('archives the release tags from 1.1.0 on that are older than the version being built, newest first', () => {
    expect(versions.map((entry) => [entry.version, entry.tag])).toEqual([
      ['1.2.0', 'v1.2.0'],
      ['1.1.0', 'v1.1.0'],
    ]);
    const [v120, v110] = versions;
    expect(v110?.readme).toBe(README_110);
    expect(v110?.knowledge).toBe(KNOWLEDGE_110);
    expect(v110?.changelog).toBe(CHANGELOG_110);
    expect(v110?.schema?.toString('utf8')).toBe(SCHEMA_110);
    expect(v110?.description).toBe('depcurfew 1.1.0 description');
    expect(v120?.knowledge).toBeUndefined();
  });

  it('says on stderr which tag it skips and why, and what an archived version lacks', () => {
    expect([...report].sort()).toEqual(
      [
        'site: skipped tag v1.0.0: the site keeps the documentation of 1.1.0 and later only',
        'site: skipped tag v1.1.1: it has no README.md',
        'site: skipped tag v2.0.0-rc.1: it is a pre-release',
        `site: skipped tag v${newer}: it is newer than the version being built, ${current}`,
        'site: skipped tag vnext: it is not a release tag v<major>.<minor>.<patch>',
        'site: tag v1.2.0 has no docs/knowledge.md, so 1.2.0/ has no knowledge base page',
        // Once for each of the two builds.
        'site: 1.1.0/index.html: README.md at tag v1.1.0 links to #nowhere, which none of its headings has; the link is shown as text',
        'site: 1.1.0/index.html: README.md at tag v1.1.0 links to #nowhere, which none of its headings has; the link is shown as text',
      ].sort(),
    );
  });

  it('builds only the current version from a directory without tags or without git', () => {
    const lines: string[] = [];
    expect(readVersions(plain, current, (line) => lines.push(line))).toEqual([]);
    expect(lines).toHaveLength(1);
    expect(lines[0]).toMatch(/^site: cannot read the git tags in .+, so only the current version is built$/u);
    const empty = mkdtempSync(join(tmpdir(), 'depcurfew-site-git-'));
    try {
      execFileSync('git', ['init', '--quiet'], { cwd: empty, env: gitEnvironment, stdio: 'ignore' });
      const none: string[] = [];
      expect(readVersions(empty, current, (line) => none.push(line))).toEqual([]);
      expect(none).toEqual([`site: no tags v* in ${empty}, so only the current version is built`]);
    } finally {
      rmSync(empty, { recursive: true, force: true });
    }
  });
});

describe('the --versions option of npm run site', () => {
  it('builds the earlier versions only when asked', () => {
    expect(siteArguments([])).toEqual({ versions: false });
    expect(siteArguments(['--versions'])).toEqual({ versions: true });
  });

  it('refuses any other argument', () => {
    expect(() => siteArguments(['--version'])).toThrow('site: unknown argument --version; npm run site takes only --versions (npm run site -- --versions)');
    expect(() => siteArguments(['--versions', 'extra'])).toThrow('site: unknown argument extra');
  });
});

describe('site with earlier versions', () => {
  it('writes the current site, the Versions page and a directory for each earlier version, and nothing else', () => {
    expect(files(site)).toEqual(FILES);
  });

  it('gives the same bytes in two builds', () => {
    const [first = '', second = ''] = outputs;
    expect(files(second)).toEqual(files(first));
    for (const name of files(first)) expect(readFileSync(join(second, name)).equals(readFileSync(join(first, name))), name).toBe(true);
  });

  it('serves the schema.json of each tag in its directory', () => {
    expect(readFileSync(join(site, '1.1.0', 'schema.json'), 'utf8')).toBe(SCHEMA_110);
    expect(readFileSync(join(site, '1.2.0', 'schema.json'), 'utf8')).toBe(SCHEMA_120);
    expect(readFileSync(join(site, 'schema.json')).equals(readFileSync(new URL('schema.json', ROOT)))).toBe(true);
  });

  it.each(HTML)('%s is a complete page whose links and anchors resolve and that loads nothing from elsewhere', (name) => {
    const html = page(name);
    checkDocument(html, name);
    checkLinks(site, name, FILES);
    checkLoadsNothing(html, name);
  });

  it.each(ROOT_PAGES)('%s links to the Versions page', (name) => {
    expect(page(name)).toContain(`<li><a href="${VERSIONS_PAGE.file}"${name === VERSIONS_PAGE.file ? ' aria-current="page"' : ''}>Versions</a></li>`);
    expect(page(name)).not.toContain('class="banner"');
  });

  it('lists the Versions page on the start page', () => {
    expect(page('index.html')).toContain(`<li><a href="${VERSIONS_PAGE.file}">${VERSIONS_PAGE.title}</a>: `);
  });

  it('lists the current version and every earlier one on the Versions page, newest first', () => {
    const html = page(VERSIONS_PAGE.file);
    expect(html).toContain('<h1 id="versions">Versions</h1>');
    const rows = [...html.matchAll(/<tr><td>(.*?)<\/td>/gu)].map((match) => match[1]);
    expect(rows).toEqual([`${current} (current)`, '1.2.0', '1.1.0']);
    expect(html).toContain(
      `<tr><td>${current} (current)</td><td><a href="index.html">Overview</a></td><td><a href="knowledge.html">Knowledge base</a></td><td><a href="${REPOSITORY}/blob/v${current}/CHANGELOG.md#${current.replaceAll('.', '')}">CHANGELOG.md</a></td><td><a href="schema.json">schema.json</a></td></tr>`,
    );
    expect(html).toContain(
      '<tr><td>1.1.0</td><td><a href="1.1.0/index.html">README</a></td><td><a href="1.1.0/knowledge.html">Knowledge base</a></td><td><a href="1.1.0/changelog.html">Changes in 1.1.0</a></td><td><a href="1.1.0/schema.json">schema.json</a></td></tr>',
    );
    expect(html).toContain('<tr><td>1.2.0</td><td><a href="1.2.0/index.html">README</a></td><td>-</td><td><a href="1.2.0/changelog.html">Changes in 1.2.0</a></td><td><a href="1.2.0/schema.json">schema.json</a></td></tr>');
  });

  it.each(ARCHIVE.filter((name) => name.endsWith('.html')))('%s has the banner of its version with links to the current documentation', (name) => {
    const version = name.split('/')[0] ?? '';
    const html = page(name);
    expect(html).toContain(
      `<main id="content">\n<p class="banner">This page documents depcurfew ${version}, an earlier version. The current version is ${current}: <a href="../index.html">its documentation</a> · <a href="../versions.html">all versions</a></p>\n`,
    );
    const sources = version === '1.1.0' ? 'README.md, docs/knowledge.md and CHANGELOG.md' : 'README.md and CHANGELOG.md';
    expect(html).toContain(`<footer class="site">\n<p>depcurfew ${version} · from ${sources} at tag v${version}, built with <code>npm run site -- --versions</code> · <a href="${REPOSITORY}/tree/v${version}">Source on GitHub</a> · MIT license</p>`);
    expect(html).toContain(`<meta name="description" content="depcurfew ${version} description">`);
    // The navigation of a version: its own pages, then the Versions page and the current documentation.
    for (const target of ['index.html', 'changelog.html', '../versions.html', '../index.html']) expect(html, target).toContain(`href="${target}"`);
    expect(html).toContain(`<li><a href="../index.html">Current version (${current})</a></li>`);
  });

  it('renders the README of a tag as one page with its own anchors and the knowledge base and changes of that tag', () => {
    const html = page('1.1.0/index.html');
    expect(html).toContain('<title>depcurfew 1.1.0</title>');
    expect(html).toContain('<h1 id="depcurfew">depcurfew</h1>');
    expect(ids(html)).toEqual(expect.arrayContaining(['github-action', 'github-action-1']));
    expect(html).toContain('<a href="#github-action">GitHub Action</a>');
    expect(html).toContain('<a href="#github-action-1">GitHub numbers it</a>');
    expect(html).toContain('but not the missing part.');
    expect(html).toContain('<a href="knowledge.html">docs/knowledge.md</a>');
    expect(html).toContain('<a href="knowledge.html#release-age-cooldown">one fact</a>');
    expect(html).toContain('<a href="changelog.html#110">the changes</a>');
    expect(html).toContain('<td>npm</td><td><code>min-release-age</code></td>');
    expect(html).not.toContain('BEGIN GENERATED');
    expect(html).toContain('<li><a href="index.html" aria-current="page">README</a></li>');
  });

  it('links files of the repository to the repository of package.json at the tag', () => {
    expect(REPOSITORY).toMatch(/^https:\/\/github\.com\/[\w.-]+\/depcurfew$/u);
    const html = page('1.1.0/index.html');
    expect(html).toContain(`<a href="${REPOSITORY}/blob/v1.1.0/src/index.ts">the source</a>`);
    expect(html).toContain(`<a href="${REPOSITORY}/tree/v1.1.0/src/knowledge">the facts</a>`);
    expect(html).toContain(`<a href="${REPOSITORY}/blob/v1.1.0/CONTRIBUTING.md">CONTRIBUTING.md</a>`);
    // A section of CHANGELOG.md that the changes page does not show.
    expect(html).toContain(`<a href="${REPOSITORY}/blob/v1.1.0/CHANGELOG.md#100">older changes</a>`);
    // The repository in package.json of the tag counts too, for a version released from another address.
    expect(html).toContain(`<a href="${REPOSITORY}/blob/v1.1.0/LICENSE">the license</a>`);
    expect(html).toContain('<a href="https://github.com/eemeli/yaml">yaml</a>');
    expect(html).not.toMatch(/\/(blob|tree)\/main\//u);
    expect(html).not.toContain('old-owner');
    // A tag without docs/knowledge.md links to the file at the tag.
    expect(page('1.2.0/index.html')).toContain(`<a href="${REPOSITORY}/blob/v1.2.0/docs/knowledge.md">docs/knowledge.md</a>`);
    expect(page('1.2.0/index.html')).not.toContain('href="knowledge.html"');
  });

  it('renders the knowledge base of the tag', () => {
    const html = page('1.1.0/knowledge.html');
    expect(html).toContain('<title>Knowledge base · depcurfew 1.1.0</title>');
    expect(html).toContain('<h1 id="package-manager-knowledge-base">Package manager knowledge base</h1>');
    expect(html).toContain('<h2 id="release-age-cooldown">Release-age cooldown</h2>');
    expect(html).toContain('<a href="https://docs.npmjs.com/cli/v11/using-npm/config#min-release-age">↗</a>');
    expect(html).toContain('<a href="index.html#github-action">README</a>');
  });

  it('shows only the section of the version from the CHANGELOG.md of its tag', () => {
    const html = page('1.1.0/changelog.html');
    expect(html).toContain('<title>Changes in 1.1.0 · depcurfew 1.1.0</title>');
    expect(html).toContain('<h1 id="110">Changes in depcurfew 1.1.0</h1>');
    expect(html).toContain('<p>Changes of one one.</p>');
    expect(html).toContain('<h2 id="new">New</h2>');
    expect(html).toContain('<li>The item of one one, see <a href="index.html#github-action">the README</a>.</li>');
    expect(html).not.toContain('one zero');
    expect(html).not.toContain('All notable changes');
    const later = page('1.2.0/changelog.html');
    expect(later).toContain('<li>The item of one two.</li>');
    expect(later).not.toContain('one one');
  });
});
