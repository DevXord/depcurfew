// The documentation of earlier releases (decision D-139): with --versions the site reads the release tags of a git
// repository and gives each one from 1.1.0 on that is older than the version being built a directory /<version>/
// with its README, its knowledge base, its CHANGELOG section and its schema, a banner on every page and a Versions
// page. The repository is a temporary one with its own tags, so the test needs no network and no tags of this
// repository.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildSite, SITE_PAGES, START_PAGES, VERSIONS_PAGE } from '../../scripts/site/build.ts';
import { readVersions, repositoryUrl, siteArguments, type ArchivedVersion } from '../../scripts/site/versions.ts';
import { checkDocument, checkLinks, checkLoadsNothing, files, ids, readPage } from './pages.ts';

const ROOT = new URL('../../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('package.json', ROOT), 'utf8')) as { version: string; repository: unknown };
const current = manifest.version;
// Links to files of the repository go to the repository that package.json names, at the tag.
const REPOSITORY = repositoryUrl(manifest.repository) ?? '';
const newer = `${Number(current.split('.')[0]) + 1}.0.0`;

// git with no configuration of the user or the system (an empty file as the global one), so signing, line endings,
// hooks paths or templates cannot get in the way.
const environment = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')));
let gitEnvironment: NodeJS.ProcessEnv = environment;
const identity = ['-c', 'user.name=depcurfew test', '-c', 'user.email=test@example.com', '-c', 'commit.gpgSign=false', '-c', 'tag.gpgSign=false'];

let repository = '';
let plain = '';
let outputs: string[] = [];
let site = '';
let report: string[] = [];
let versions: ArchivedVersion[] = [];

function git(...args: string[]): void {
  execFileSync('git', [...identity, ...args], { cwd: repository, env: gitEnvironment, stdio: 'ignore' });
}

function write(files: Record<string, string | null>): void {
  for (const [path, content] of Object.entries(files)) {
    const target = join(repository, ...path.split('/'));
    if (content === null) rmSync(target, { force: true });
    else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
}

function commit(tag: string, files: Record<string, string | null>, annotated = false): void {
  write(files);
  git('add', '--all');
  git('commit', '--quiet', '--allow-empty', '-m', tag);
  if (annotated) git('tag', '-a', tag, '-m', tag);
  else git('tag', tag);
}

